COMMENT ON TABLE workflow_instances IS 'Specific data entity instances being processed through workflows (e.g., Customer: John Doe)';
COMMENT ON TABLE timeline_event_workflow_mappings IS 'Maps individual timeline events to specific workflow instances with detailed context';
