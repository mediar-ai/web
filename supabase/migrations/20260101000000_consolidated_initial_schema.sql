-- =============================================================================
-- Table: users
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.users (
  id uuid DEFAULT gen_random_uuid() NOT NULL,
  clerk_user_id text NOT NULL,
  email text,
  role text DEFAULT 'viewer'::text NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT users_pkey PRIMARY KEY (id),
  CONSTRAINT users_clerk_user_id_key UNIQUE (clerk_user_id)
);
COMMENT ON TABLE public.users IS 'Stores user information for dashboard viewers, linked to Clerk accounts.';
COMMENT ON COLUMN public.users.clerk_user_id IS 'The user ID from the Clerk authentication service.';
COMMENT ON COLUMN public.users.role IS 'The access role of the user (e.g., admin, viewer).';

