-- Table: low_level_workflow_analyses
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.low_level_workflow_analyses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  session_id TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  client_timestamp TIMESTAMPTZ,
  llm_structured_output JSONB,
  context_metadata JSONB
);
ALTER TABLE public.low_level_workflow_analyses ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow user to view their own analyses" ON public.low_level_workflow_analyses FOR SELECT TO authenticated USING (auth.uid() = user_id);
CREATE POLICY "Allow user to insert their own analyses" ON public.low_level_workflow_analyses FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);

