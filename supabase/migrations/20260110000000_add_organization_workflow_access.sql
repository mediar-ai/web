-- Function to check if an organization has access to a workflow
CREATE OR REPLACE FUNCTION check_workflow_access(
    p_workflow_id bigint,
    p_organization_id text
) RETURNS boolean AS $$
DECLARE
    v_has_access boolean;
BEGIN
    SELECT EXISTS(
        SELECT 1 FROM public.deployed_workflows w
        WHERE w.id = p_workflow_id
        AND (
            w.organization_id = p_organization_id OR
            EXISTS (
                SELECT 1 FROM public.workflow_organization_access woa
                WHERE woa.workflow_id = w.id
                AND woa.organization_id = p_organization_id
            )
        )
    ) INTO v_has_access;

    RETURN v_has_access;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to grant workflow access to an organization
CREATE OR REPLACE FUNCTION grant_workflow_access(
    p_workflow_id bigint,
    p_organization_id text,
    p_access_level text DEFAULT 'read',
    p_granted_by uuid DEFAULT auth.uid()
) RETURNS void AS $$
BEGIN
    INSERT INTO public.workflow_organization_access (
        workflow_id,
        organization_id,
        access_level,
        granted_by,
        granted_at
    ) VALUES (
        p_workflow_id,
        p_organization_id,
        p_access_level,
        p_granted_by,
        now()
    )
    ON CONFLICT (workflow_id, organization_id)
    DO UPDATE SET
        access_level = EXCLUDED.access_level,
        granted_by = EXCLUDED.granted_by,
        granted_at = EXCLUDED.granted_at;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to revoke workflow access from an organization
CREATE OR REPLACE FUNCTION revoke_workflow_access(
    p_workflow_id bigint,
    p_organization_id text
) RETURNS void AS $$
BEGIN
    DELETE FROM public.workflow_organization_access
    WHERE workflow_id = p_workflow_id
    AND organization_id = p_organization_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

