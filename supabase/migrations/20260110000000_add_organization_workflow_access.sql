-- Table: workflow_organization_access
-- This table manages which organizations have access to which workflows
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.workflow_organization_access (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    workflow_id bigint NOT NULL REFERENCES public.deployed_workflows(id) ON DELETE CASCADE,
    organization_id text NOT NULL, -- Clerk organization ID
    access_level text DEFAULT 'read' CHECK (access_level IN ('read', 'write', 'admin')),
    granted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    granted_at timestamp with time zone DEFAULT now(),

    -- Ensure unique access per workflow-organization pair
    UNIQUE(workflow_id, organization_id)
);

