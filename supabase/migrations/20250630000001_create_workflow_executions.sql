-- Migration: Create workflow execution tracking table
-- Created: 2025-06-30
-- Description: Tracks individual workflow executions for remote clients

CREATE TABLE IF NOT EXISTS public.workflow_executions (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    
    -- Workflow reference
    workflow_id bigint NOT NULL REFERENCES public.deployed_workflows(id) ON DELETE CASCADE,
    
    -- Client information
    client_id text NOT NULL, -- API key or client identifier
    client_ip inet,
    user_agent text,
    
    -- Execution details
    status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'completed', 'failed', 'cancelled', 'timeout')),
    execution_params jsonb NOT NULL DEFAULT '{}', -- Input parameters provided by client
    
    -- Results and logs
    results jsonb, -- Final execution results
    execution_logs text[], -- Step-by-step execution logs
    error_message text, -- Error details if failed
    screenshots text[], -- Base64 encoded screenshots
    
    -- Timing
    queued_at timestamp with time zone DEFAULT now(),
    started_at timestamp with time zone,
    completed_at timestamp with time zone,
    execution_duration_seconds integer,
    
    -- Modal integration
    modal_call_id text, -- Modal function call ID for tracking
    modal_logs jsonb, -- Raw Modal execution logs
    
    -- Billing and usage
    compute_cost_cents integer DEFAULT 0, -- Cost in cents
    priority integer DEFAULT 5 CHECK (priority BETWEEN 1 AND 10), -- 1=highest, 10=lowest
    
    -- Metadata
    created_at timestamp with time zone DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now()
);

