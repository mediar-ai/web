def update_workflow_version_trigger(conn):
    """Update the workflow versioning trigger."""
    print("🔧 Updating workflow versioning trigger...")
    
    with conn.cursor() as cur:
        # Drop old trigger if it exists
        cur.execute("""
            DROP TRIGGER IF EXISTS trigger_autoincrement_workflow_version 
            ON public.deployed_workflows;
        """)
        
        # Create new version creation function
        cur.execute("""
            CREATE OR REPLACE FUNCTION create_new_workflow_version()
            RETURNS TRIGGER AS $$
            DECLARE
                new_version_number text;
                new_version_id bigint;
            BEGIN
                -- Only create new version if automation_sequence actually changed
                IF NEW.automation_sequence IS DISTINCT FROM OLD.automation_sequence THEN
                    -- Generate next version number
                    new_version_number := increment_version(OLD.version);
                    
                    -- Create new version record
                    INSERT INTO public.deployed_workflow_versions 
                    (workflow_id, version_number, automation_sequence, is_active, created_by, change_notes)
                    VALUES (NEW.id, new_version_number, NEW.automation_sequence, false, COALESCE(NEW.created_by::text, 'system'), 'Updated via automation_sequence change')
                    RETURNING id INTO new_version_id;
                    
                    -- Deactivate old version
                    UPDATE public.deployed_workflow_versions 
                    SET is_active = false 
                    WHERE workflow_id = NEW.id AND id != new_version_id;
                    
                    -- Activate new version
                    UPDATE public.deployed_workflow_versions 
                    SET is_active = true 
                    WHERE id = new_version_id;
                    
                    -- Update workflow metadata
                    NEW.version = new_version_number;
                    NEW.total_versions = OLD.total_versions + 1;
                    NEW.current_version_id = new_version_id;
                END IF;
                
                RETURN NEW;
            END;
            $$ LANGUAGE plpgsql;
        """)
        
        # Create new trigger
        cur.execute("""
            CREATE TRIGGER trigger_create_workflow_version
            BEFORE UPDATE ON public.deployed_workflows
            FOR EACH ROW EXECUTE FUNCTION create_new_workflow_version();
        """)
        
        cur.execute("""
            COMMENT ON FUNCTION create_new_workflow_version() IS 
            'Creates new version when automation_sequence changes, maintains version history';
        """)
        
        print("✅ Successfully updated workflow versioning trigger")

def create_compatibility_views(conn):
    """Create views for backward compatibility."""
    print("📝 Creating compatibility views...")
    
    with conn.cursor() as cur:
        # Create view that includes automation_sequence from current version
        cur.execute("""
            CREATE OR REPLACE VIEW public.deployed_workflows_with_sequence AS
            SELECT 
                w.id, w.name, w.description, w.status, w.category,
                w.successful_runs, w.failed_runs, w.cancelled_runs, w.total_executions,
                w.estimated_duration_seconds, w.workflow_type, w.parent_workflow_id, w.display_order,
                w.created_by, w.created_at, w.updated_at,
                w.current_version_id, w.total_versions,
                v.automation_sequence,
                v.version_number as version,
                v.change_notes as current_version_notes
            FROM public.deployed_workflows w
            LEFT JOIN public.deployed_workflow_versions v ON w.current_version_id = v.id;
        """)
        
        # Create view for execution history with version info
        cur.execute("""
            CREATE OR REPLACE VIEW public.workflow_execution_history AS
            SELECT 
                e.*,
                w.name as workflow_name,
                v.version_number,
                v.change_notes as version_notes
            FROM public.workflow_executions e
            JOIN public.deployed_workflows w ON e.workflow_id = w.id
            LEFT JOIN public.deployed_workflow_versions v ON e.workflow_version_id = v.id;
        """)
        
        # Add comments
        cur.execute("""
            COMMENT ON VIEW public.deployed_workflows_with_sequence IS 
            'Backward compatibility view that includes automation_sequence from current active version';
        """)
        
        cur.execute("""
            COMMENT ON VIEW public.workflow_execution_history IS 
            'Complete execution history with version information for traceability';
        """)
        
        print("✅ Successfully created compatibility views")

def create_version_management_functions(conn):
    """Create functions for version management operations."""
    print("🔧 Creating version management functions...")
    
    with conn.cursor() as cur:
        # Function to activate a specific version
        cur.execute("""
            CREATE OR REPLACE FUNCTION activate_workflow_version(
                p_workflow_id bigint,
                p_version_number text
            ) RETURNS boolean AS $$
            DECLARE
                target_version_id bigint;
            BEGIN
                -- Find the target version
                SELECT id INTO target_version_id
                FROM public.deployed_workflow_versions
                WHERE workflow_id = p_workflow_id AND version_number = p_version_number;
                
                IF target_version_id IS NULL THEN
                    RAISE EXCEPTION 'Version % not found for workflow %', p_version_number, p_workflow_id;
                END IF;
                
                -- Deactivate all versions for this workflow
                UPDATE public.deployed_workflow_versions
                SET is_active = false
                WHERE workflow_id = p_workflow_id;
                
                -- Activate target version
                UPDATE public.deployed_workflow_versions
                SET is_active = true
                WHERE id = target_version_id;
                
                -- Update main workflow record
                UPDATE public.deployed_workflows
                SET current_version_id = target_version_id,
                    version = p_version_number,
                    updated_at = now()
                WHERE id = p_workflow_id;
                
                RETURN true;
            END;
            $$ LANGUAGE plpgsql SECURITY DEFINER;
        """)
        
        # Function to get version history
        cur.execute("""
            CREATE OR REPLACE FUNCTION get_workflow_version_history(p_workflow_id bigint)
            RETURNS TABLE(
                version_id bigint,
                version_number text,
                is_active boolean,
                created_at timestamptz,
                change_notes text,
                execution_count bigint
            ) AS $$
            BEGIN
                RETURN QUERY
                SELECT 
                    v.id,
                    v.version_number,
                    v.is_active,
                    v.created_at,
                    v.change_notes,
                    COUNT(e.id) as execution_count
                FROM public.deployed_workflow_versions v
                LEFT JOIN public.workflow_executions e ON v.id = e.workflow_version_id
                WHERE v.workflow_id = p_workflow_id
                GROUP BY v.id, v.version_number, v.is_active, v.created_at, v.change_notes
                ORDER BY v.created_at DESC;
            END;
            $$ LANGUAGE plpgsql SECURITY DEFINER;
        """)
        
        # Add comments
        cur.execute("""
            COMMENT ON FUNCTION activate_workflow_version(bigint, text) IS 
            'Activates a specific version of a workflow (rollback/rollforward)';
        """)
        
        cur.execute("""
            COMMENT ON FUNCTION get_workflow_version_history(bigint) IS 
            'Returns complete version history for a workflow with execution counts';
        """)
        
        print("✅ Successfully created version management functions")

