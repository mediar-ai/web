def migrate_existing_data(conn):
    """Migrate existing automation_sequence data to versions table."""
    print("📦 Migrating existing automation sequences to versions table...")
    
    with conn.cursor() as cur:
        # Check if we have any workflows to migrate
        cur.execute("SELECT COUNT(*) FROM deployed_workflows")
        result = cur.fetchone()
        workflow_count = result[0] if result else 0
        
        if workflow_count == 0:
            print("  No workflows to migrate")
            return
        
        print(f"  Found {workflow_count} workflows to migrate...")
        
        # Migrate existing data to versions table
        cur.execute("""
            INSERT INTO public.deployed_workflow_versions 
            (workflow_id, version_number, automation_sequence, is_active, created_by, change_notes)
            SELECT 
                id, 
                COALESCE(version, '1.0.0'), 
                automation_sequence, 
                true, 
                COALESCE(created_by::text, 'system'),
                'Initial version migrated from deployed_workflows table'
            FROM public.deployed_workflows
            WHERE id NOT IN (
                SELECT DISTINCT workflow_id 
                FROM public.deployed_workflow_versions
            );
        """)
        
        migrated_count = cur.rowcount
        print(f"  Migrated {migrated_count} workflow versions")
        
        # Update current_version_id references
        cur.execute("""
            UPDATE public.deployed_workflows 
            SET current_version_id = v.id,
                total_versions = 1
            FROM public.deployed_workflow_versions v 
            WHERE deployed_workflows.id = v.workflow_id 
            AND v.is_active = true
            AND deployed_workflows.current_version_id IS NULL;
        """)
        
        updated_count = cur.rowcount
        print(f"  Updated {updated_count} workflow references")
        
        print("✅ Successfully migrated existing data")

