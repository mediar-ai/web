def create_workflow_versions_table(conn):
    """Create the deployed_workflow_versions table."""
    print("📝 Creating deployed_workflow_versions table...")
    
    with conn.cursor() as cur:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS public.deployed_workflow_versions (
                id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                workflow_id bigint NOT NULL REFERENCES public.deployed_workflows(id) ON DELETE CASCADE,
                version_number text NOT NULL,
                automation_sequence jsonb NOT NULL,
                is_active boolean DEFAULT false,
                created_at timestamp with time zone DEFAULT now(),
                created_by text,
                change_notes text,
                CONSTRAINT unique_workflow_version UNIQUE(workflow_id, version_number)
            );
        """)
        
        # Create indexes for efficient querying
        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_workflow_versions_workflow_id 
            ON public.deployed_workflow_versions(workflow_id);
        """)
        
        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_workflow_versions_active 
            ON public.deployed_workflow_versions(workflow_id, is_active) 
            WHERE is_active = true;
        """)
        
        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_workflow_versions_created_at 
            ON public.deployed_workflow_versions(created_at);
        """)
        
        # Add RLS policies
        cur.execute("""
            ALTER TABLE public.deployed_workflow_versions ENABLE ROW LEVEL SECURITY;
        """)
        
        # Create RLS policies (drop first if they exist)
        cur.execute("""
            DROP POLICY IF EXISTS "Users can read workflow versions" 
            ON public.deployed_workflow_versions;
        """)
        
        cur.execute("""
            CREATE POLICY "Users can read workflow versions" 
            ON public.deployed_workflow_versions
            FOR SELECT USING (true);
        """)
        
        cur.execute("""
            DROP POLICY IF EXISTS "Authenticated users can create versions" 
            ON public.deployed_workflow_versions;
        """)
        
        cur.execute("""
            CREATE POLICY "Authenticated users can create versions" 
            ON public.deployed_workflow_versions
            FOR INSERT WITH CHECK (true);
        """)
        
        # Add comments
        cur.execute("""
            COMMENT ON TABLE public.deployed_workflow_versions IS 
            'Stores all versions of workflow automation sequences with full history';
        """)
        
        cur.execute("""
            COMMENT ON COLUMN public.deployed_workflow_versions.automation_sequence IS 
            'Complete workflow definition for this specific version';
        """)
        
        cur.execute("""
            COMMENT ON COLUMN public.deployed_workflow_versions.is_active IS 
            'Only one version per workflow can be active at a time';
        """)
        
        print("✅ Successfully created deployed_workflow_versions table")

